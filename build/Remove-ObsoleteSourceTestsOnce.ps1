<#
.SYNOPSIS
    One-time, explicit cleanup of leftover non-PowerShell source tests from an overlaid LocalGPT checkout.
.DESCRIPTION
    Only files under the repository's tests directory whose extensions are
    rejected by Assert-RepositoryPowerShellBoundary.ps1 are eligible.
    First run previews all candidates; -Apply removes exactly those candidates.
    Application/runtime Python, build guards, user data, and other files are not touched.
.EXAMPLE
    powershell -NoProfile -ExecutionPolicy Bypass -File .\build\Remove-ObsoleteSourceTestsOnce.ps1
.EXAMPLE
    powershell -NoProfile -ExecutionPolicy Bypass -File .\build\Remove-ObsoleteSourceTestsOnce.ps1 -Apply
.EXAMPLE
    powershell -NoProfile -ExecutionPolicy Bypass -File .\LocalGPT-OneTime-Cleanup.ps1 -RepositoryRoot 'C:\Path\To\LocalGPT\src' -Apply
#>
[CmdletBinding()]
param(
    [string]$RepositoryRoot = '',
    [switch]$Apply
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

if ([string]::IsNullOrWhiteSpace($RepositoryRoot)) {
    $candidateRoot = [IO.Path]::GetFullPath((Join-Path $PSScriptRoot '..'))
    if ((Test-Path -LiteralPath (Join-Path $candidateRoot 'Directory.Build.targets') -PathType Leaf) -and
        (Test-Path -LiteralPath (Join-Path $candidateRoot 'build/Assert-RepositoryPowerShellBoundary.ps1') -PathType Leaf)) {
        $RepositoryRoot = $candidateRoot
    }
    else {
        $RepositoryRoot = (Get-Location).Path
    }
}
$RepositoryRoot = [IO.Path]::GetFullPath($RepositoryRoot)

# Refuse to run in arbitrary folders or the wrong repository.
$boundary = Join-Path $RepositoryRoot 'build/Assert-RepositoryPowerShellBoundary.ps1'
$project = Join-Path $RepositoryRoot 'src/LocalGPT/LocalGPT.csproj'
if (-not (Test-Path -LiteralPath $boundary -PathType Leaf) -or
    -not (Test-Path -LiteralPath $project -PathType Leaf)) {
    throw "Not a LocalGPT source root: $RepositoryRoot. Supply -RepositoryRoot pointing at the folder containing Directory.Build.targets."
}

$testRoot = Join-Path $RepositoryRoot 'tests'
if (-not (Test-Path -LiteralPath $testRoot -PathType Container)) {
    Write-Host 'No tests directory exists; nothing to clean.'
    return
}

# Keep this in sync with the repository's PowerShell boundary. No version lists,
# file-name lists, or hand-maintained hashes are needed for later releases.
$rejectedExtensions = @('.py', '.pyc', '.pyo', '.cjs', '.mjs', '.js')
$obsolete = @(Get-ChildItem -LiteralPath $testRoot -Recurse -File -Force |
    Where-Object { $_.Extension -in $rejectedExtensions } |
    Sort-Object -Property FullName)

if ($obsolete.Count -eq 0) {
    Write-Host 'LocalGPT PowerShell-only test boundary: no obsolete test files found.'
    return
}

Write-Host "Found $($obsolete.Count) obsolete source-test file(s) under '$testRoot':"
foreach ($file in $obsolete) {
    Write-Host ('  ' + $file.FullName.Substring($RepositoryRoot.Length + 1))
}

if (-not $Apply) {
    Write-Host 'PREVIEW ONLY: no files removed. Rerun with -Apply to perform the one-time cleanup.'
    return
}

foreach ($file in $obsolete) {
    # Remove individual files only, never an entire test tree.
    Remove-Item -LiteralPath $file.FullName -Force -ErrorAction Stop
}

# Clean up generated bytecode cache directories only if empty after file deletion.
$cacheDirs = @(Get-ChildItem -LiteralPath $testRoot -Recurse -Directory -Force |
    Where-Object { $_.Name -eq '__pycache__' } |
    Sort-Object -Property FullName -Descending)
foreach ($directory in $cacheDirs) {
    $remaining = @(Get-ChildItem -LiteralPath $directory.FullName -Force)
    if ($remaining.Count -eq 0) {
        Remove-Item -LiteralPath $directory.FullName -Force -ErrorAction Stop
    }
}

$stillRejected = @(Get-ChildItem -LiteralPath $testRoot -Recurse -File -Force |
    Where-Object { $_.Extension -in $rejectedExtensions })
if ($stillRejected.Count -gt 0) {
    throw "Cleanup incomplete: $($stillRejected.Count) forbidden test file(s) remain."
}
Write-Host "One-time cleanup removed $($obsolete.Count) obsolete source-test file(s). Existing PowerShell checks were preserved."
