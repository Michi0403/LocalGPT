# Council route defaults must have one persisted owner. This guard is source-only and
# intentionally validates architecture, not provider hardware or model performance.
[CmdletBinding()]
param(
    [string]$RepositoryRoot = (Split-Path -Parent $PSScriptRoot)
)
Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

function Assert-SourceContract {
    param(
        [string]$RelativePath,
        [string]$RequiredPattern,
        [string]$ForbiddenPattern,
        [string]$Explanation
    )

    $sourcePath = Join-Path $RepositoryRoot $RelativePath
    if (-not (Test-Path -LiteralPath $sourcePath -PathType Leaf)) {
        throw ("{0}(1,1): error LOCALGPT_COUNCIL_POLICY: Missing required policy source. Restore {1} and delegate budgets to the Council configuration service." -f $sourcePath, $RelativePath)
    }
    $source = [System.IO.File]::ReadAllText($sourcePath)
    if (-not [string]::IsNullOrEmpty($RequiredPattern) -and $source -notmatch $RequiredPattern) {
        throw ("{0}(1,1): error LOCALGPT_COUNCIL_POLICY: {1}. Restore the runtime-policy/service delegation; do not replace it with compiled token constants." -f $sourcePath, $Explanation)
    }
    if (-not [string]::IsNullOrEmpty($ForbiddenPattern) -and $source -match $ForbiddenPattern) {
        $line = ($source.Substring(0, $source.IndexOf($Matches[0], [System.StringComparison]::Ordinal)) -split "`n").Count
        throw ("{0}({1},1): error LOCALGPT_COUNCIL_POLICY: {2}. Use persisted Council limits, provider facts or explicit user roads, never an implicit compiled ceiling." -f $sourcePath, $line, $Explanation)
    }
}

