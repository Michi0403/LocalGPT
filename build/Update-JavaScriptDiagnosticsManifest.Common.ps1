[CmdletBinding()]
param(
    [Parameter(Mandatory = $true)][string]$RepositoryRoot,
    [Parameter(Mandatory = $true)][string]$JavaScriptRoot,
    [Parameter(Mandatory = $true)][string]$ManifestPath,
    [string]$ProductName = "Application"
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

function Get-NormalizedTextSha256([string]$Path) {
    $text = [IO.File]::ReadAllText($Path)
    $normalized = $text.Replace("`r`n", "`n").Replace("`r", "`n")
    $encoding = New-Object Text.UTF8Encoding($false)
    $sha256 = [Security.Cryptography.SHA256]::Create()
    try {
        return ([BitConverter]::ToString($sha256.ComputeHash($encoding.GetBytes($normalized)))).Replace('-', '').ToLowerInvariant()
    }
    finally {
        $sha256.Dispose()
    }
}

$repositoryRootFull = [IO.Path]::GetFullPath($RepositoryRoot).TrimEnd([IO.Path]::DirectorySeparatorChar, [IO.Path]::AltDirectorySeparatorChar)
$javaScriptRootFull = [IO.Path]::GetFullPath($JavaScriptRoot)
$manifestFull = [IO.Path]::GetFullPath($ManifestPath)

if (-not (Test-Path -LiteralPath $javaScriptRootFull -PathType Container)) {
    throw "$ProductName JavaScript root does not exist: $javaScriptRootFull"
}

$maintained = @(
    Get-ChildItem -LiteralPath $javaScriptRootFull -File -Filter '*.js' |
        Where-Object { -not $_.Name.EndsWith('.example.js', [StringComparison]::OrdinalIgnoreCase) } |
        Sort-Object FullName
)
if ($maintained.Count -eq 0) { throw "$ProductName has no maintained JavaScript files under $javaScriptRootFull" }

$lines = New-Object 'System.Collections.Generic.List[string]'
$lines.Add("# $ProductName maintained browser JavaScript diagnostics inventory.")
$lines.Add('# Generated by build/Update-JavaScriptDiagnosticsManifest.ps1. Hashes normalize CRLF/CR to LF before SHA-256.')
$lines.Add('# Build scripts refresh this manifest before validation; direct IDE/MSBuild builds validate it without silently blessing changes.')
$lines.Add('')

foreach ($file in $maintained) {
    $relative = $file.FullName.Substring($repositoryRootFull.Length + 1).Replace([char]'\', [char]'/')
    $hash = Get-NormalizedTextSha256 $file.FullName
    $lines.Add("$hash  $relative")
}

$newText = ($lines -join "`n") + "`n"
$encoding = New-Object Text.UTF8Encoding($false)
$oldText = if (Test-Path -LiteralPath $manifestFull -PathType Leaf) { [IO.File]::ReadAllText($manifestFull).Replace("`r`n", "`n").Replace("`r", "`n") } else { '' }
if ($oldText -ne $newText) {
    $manifestDirectory = Split-Path -Parent $manifestFull
    if (-not (Test-Path -LiteralPath $manifestDirectory -PathType Container)) { New-Item -ItemType Directory -Path $manifestDirectory -Force | Out-Null }
    [IO.File]::WriteAllText($manifestFull, $newText, $encoding)
    Write-Host "Refreshed $ProductName JavaScript diagnostics SHA-256 manifest for $($maintained.Count) maintained browser file(s)." -ForegroundColor Green
}
else {
    Write-Host "$ProductName JavaScript diagnostics SHA-256 manifest is already current for $($maintained.Count) maintained browser file(s)." -ForegroundColor DarkGreen
}
