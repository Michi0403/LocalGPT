#!/usr/bin/env python3
"""Checks broad XML-summary coverage for maintained C# types and methods."""
from __future__ import annotations

import argparse
import re
from pathlib import Path

DECLARATION = re.compile(
    r"^(?P<indent>\s*)(?P<attrs>(?:\[[^\]]+\]\s*)*)(?P<mods>(?:(?:public|protected|internal|private|static|sealed|abstract|partial|virtual|override|async|unsafe|readonly|required|new|extern)\s+)+)(?P<body>.+)$"
)
TYPE_DECLARATION = re.compile(r"\b(class|interface|struct|record(?:\s+class|\s+struct)?|enum|delegate)\s+([A-Za-z_][A-Za-z0-9_]*)")
METHOD_NAME = re.compile(r"(?:operator\s*[^\s(]+|([A-Za-z_][A-Za-z0-9_]*))\s*(?:<[^>{};=]+>)?\s*\(")
PROPERTY_NAME = re.compile(r"([A-Za-z_][A-Za-z0-9_]*)\s*(?:\{|=>)")
EVENT_NAME = re.compile(r"\bevent\s+[^;=]+\s+([A-Za-z_][A-Za-z0-9_]*)")
FIELD_NAME = re.compile(r"([A-Za-z_][A-Za-z0-9_]*)\s*(?:=|;)")
IMPLICIT_INTERFACE_METHOD = re.compile(
    r"^(?P<indent>\s*)(?!//|/\*|\*|\[)(?P<body>(?!(?:if|for|foreach|while|switch|catch|using|lock|return|throw)\b).+?\b(?P<name>[A-Za-z_][A-Za-z0-9_]*)\s*(?:<[^>{};=]+>)?\s*\()"
)
TYPE_KINDS = {"class", "interface", "struct", "record", "enum", "delegate"}


def raw_string_line_mask(lines: list[str]) -> list[bool]:
    """Marks lines whose declaration-looking text is raw-string content rather than C# source."""
    mask: list[bool] = []
    delimiter: int | None = None
    for line in lines:
        mask.append(delimiter is not None)
        for match in re.finditer(r'"{3,}', line):
            length = len(match.group())
            if delimiter is None:
                delimiter = length
            elif length >= delimiter:
                delimiter = None
    return mask


def is_generated(path: Path, text: str) -> bool:
    lower = path.name.lower()
    return lower.endswith(".designer.cs") or lower.endswith(".g.cs") or "<auto-generated" in text[:2000].lower()


def attribute_start(lines: list[str], declaration_index: int) -> int:
    insertion = declaration_index
    index = declaration_index - 1
    while index >= 0 and not lines[index].strip():
        index -= 1
    while index >= 0:
        stripped = lines[index].strip()
        if not stripped.endswith("]"):
            break
        balance = 0
        while index >= 0:
            current = lines[index].strip()
            balance += current.count("]") - current.count("[")
            if current.startswith("[") and balance <= 0:
                insertion = index
                index -= 1
                break
            index -= 1
        while index >= 0 and not lines[index].strip():
            index -= 1
    return insertion


def has_docs(lines: list[str], insertion: int) -> bool:
    index = insertion - 1
    while index >= 0 and not lines[index].strip():
        index -= 1
    return index >= 0 and lines[index].lstrip().startswith("///")


def classify(body: str) -> str | None:
    type_match = TYPE_DECLARATION.search(body)
    if type_match:
        return type_match.group(1).split()[-1]
    if EVENT_NAME.search(body):
        return "event"
    property_match = PROPERTY_NAME.search(body)
    first_parenthesis = body.find("(")
    property_marker = min([value for value in (body.find("{"), body.find("=>")) if value >= 0], default=-1)
    if property_match and property_marker >= 0 and (first_parenthesis < 0 or property_marker < first_parenthesis):
        return "property"
    if METHOD_NAME.search(body):
        return "method"
    if FIELD_NAME.search(body):
        return "field"
    return None


def is_public_api(mods: str) -> bool:
    tokens = set(mods.split())
    return "public" in tokens or "protected" in tokens


def interface_line_ranges(lines: list[str]) -> list[tuple[int, int]]:
    ranges: list[tuple[int, int]] = []
    for start, line in enumerate(lines):
        if not re.search(r"\binterface\s+[A-Za-z_]", line):
            continue
        depth = 0
        opened = False
        for index in range(start, len(lines)):
            depth += lines[index].count("{") - lines[index].count("}")
            if "{" in lines[index]:
                opened = True
            if opened and depth <= 0:
                ranges.append((start, index))
                break
    return ranges


def inside_ranges(index: int, ranges: list[tuple[int, int]]) -> bool:
    return any(start < index < end for start, end in ranges)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("root", type=Path)
    args = parser.parse_args()
    failures: list[str] = []
    declarations = 0
    for path in sorted(args.root.rglob("*.cs")):
        if "obj" in path.parts or "bin" in path.parts:
            continue
        text = path.read_text(encoding="utf-8-sig", errors="replace")
        if is_generated(path, text):
            continue
        lines = text.splitlines()
        raw_lines = raw_string_line_mask(lines)
        interface_ranges = interface_line_ranges(lines)
        for index, line in enumerate(lines):
            if raw_lines[index]:
                continue
            match = DECLARATION.match(line)
            target = False
            if match:
                kind = classify(match.group("body"))
                target = bool(kind and (kind in TYPE_KINDS or kind == "method" or is_public_api(match.group("mods"))))
            elif inside_ranges(index, interface_ranges):
                implicit = IMPLICIT_INTERFACE_METHOD.match(line)
                target = bool(implicit and (";" in line or line.rstrip().endswith("(")))
            if not target:
                continue
            declarations += 1
            insertion = attribute_start(lines, index)
            if not has_docs(lines, insertion):
                failures.append(f"{path.as_posix()}:{index + 1}: {line.strip()}")
    if failures:
        print("XML documentation coverage failed:")
        for failure in failures[:300]:
            print(f"  - {failure}")
        if len(failures) > 300:
            print(f"  - ... and {len(failures) - 300} more")
        return 1
    print(f"XML documentation coverage passed for {declarations} maintained C# type/method and public API declarations.")
    return 0

if __name__ == "__main__":
    raise SystemExit(main())
