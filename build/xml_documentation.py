def sanitize(text:str)->list[str]:
 out=[]; cur=[]; i=0; state='normal'; raw_len=0
 def eol():
  nonlocal cur; out.append(''.join(cur)); cur=[]
 while i<len(text):
  c=text[i]; n=text[i+1] if i+1<len(text) else ''
  if state=='line':
   if c=='\n': eol(); state='normal'
   else: cur.append(' ')
   i+=1; continue
  if state=='block':
   if c=='*' and n=='/': cur.extend('  '); i+=2; state='normal'; continue
   if c=='\n': eol()
   else: cur.append(' ')
   i+=1; continue
  if state=='str':
   if c=='\\': cur.append(' '); i+=1; 
   if i<len(text) and state=='str' and c=='\\':
    if i<len(text): cur.append(' '); i+=1
    continue
   if c=='"': state='normal'
   if c=='\n': eol()
   else: cur.append(' ')
   i+=1; continue
  if state=='verb':
   if c=='"' and n=='"': cur.extend('  '); i+=2; continue
   if c=='"': state='normal'
   if c=='\n': eol()
   else: cur.append(' ')
   i+=1; continue
  if state=='char':
   if c=='\\': cur.append(' '); i+=1; 
   if i<len(text) and state=='char' and c=='\\':
    if i<len(text): cur.append(' '); i+=1
    continue
   if c=="'": state='normal'
   if c=='\n': eol()
   else: cur.append(' ')
   i+=1; continue
  if state=='raw':
   if c=='"':
    j=i
    while j<len(text) and text[j]=='"': j+=1
    q=j-i
    if q>=raw_len: cur.extend(' '*q); i=j; state='normal'; raw_len=0; continue
   if c=='\n': eol()
   else: cur.append(' ')
   i+=1; continue
  # normal
  if c=='/' and n=='/': cur.extend('  '); i+=2; state='line'; continue
