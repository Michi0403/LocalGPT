using System.CodeDom;
using System.CodeDom.Compiler;
using LocalGPT.BusinessObjects;
using LocalGPT.Interfaces;
using Microsoft.CSharp;

namespace LocalGPT.Services;

/// <summary>
/// Shares one typed CodeDOM emitter between the reviewed project-generation workflow and
/// the opt-in session sandbox source preview. This service does not build or run user code.
/// </summary>
public sealed class CodeDomSourceService : ICodeDomSourceService
{
    /// <inheritdoc />
    public string GenerateCSharpSource(CodeDomTypeSpec spec) => Generate(spec, includeSandboxEntryPoint: false);

    /// <inheritdoc />
    public string GenerateCSharpSandboxProgram(CodeDomTypeSpec spec) => Generate(spec, includeSandboxEntryPoint: true);

    /// <summary>Generates one typed source unit and an optional isolated-execution entry point.</summary>
    /// <param name="spec">Declaration supplied by the current review or editor.</param>
    /// <param name="includeSandboxEntryPoint">Whether to emit an executable test harness.</param>
    /// <returns>A generated, human-reviewable source file.</returns>
    private string Generate(CodeDomTypeSpec spec, bool includeSandboxEntryPoint)
    {
        ArgumentNullException.ThrowIfNull(spec);
        using var provider = new CSharpCodeProvider();
        ValidateNamespace(provider, spec.Namespace);
        ValidateIdentifier(provider, spec.TypeName, nameof(spec.TypeName));
        ValidateIdentifier(provider, spec.MethodName, nameof(spec.MethodName));
        if (spec.TypeName == "Program" && includeSandboxEntryPoint)
            throw new ArgumentException("Use a type name other than Program for a runnable CodeDOM example.");
        if ((spec.MethodResult?.Length ?? 0) > 16_384 || (spec.Summary?.Length ?? 0) > 4_096)
            throw new ArgumentException("The CodeDOM declaration exceeds the source-preview limits.");

        var unit = new CodeCompileUnit();
        var ns = new CodeNamespace(spec.Namespace);
        ns.Imports.Add(new CodeNamespaceImport("System"));
        unit.Namespaces.Add(ns);

        var type = new CodeTypeDeclaration(spec.TypeName)
        {
            IsClass = true,
            TypeAttributes = System.Reflection.TypeAttributes.Public | System.Reflection.TypeAttributes.Sealed
        };
        if (!string.IsNullOrWhiteSpace(spec.Summary))
            type.Comments.Add(new CodeCommentStatement(spec.Summary));
        ns.Types.Add(type);

        var method = new CodeMemberMethod
        {
            Name = spec.MethodName,
            Attributes = MemberAttributes.Public | MemberAttributes.Final,
            ReturnType = new CodeTypeReference(typeof(string))
        };
        method.Statements.Add(new CodeMethodReturnStatement(new CodePrimitiveExpression(spec.MethodResult ?? string.Empty)));
        type.Members.Add(method);

        if (includeSandboxEntryPoint)
        {
            var mainType = new CodeTypeDeclaration("Program")
            {
                IsClass = true,
                TypeAttributes = System.Reflection.TypeAttributes.Public | System.Reflection.TypeAttributes.Sealed
            };
            var main = new CodeMemberMethod
            {
                Name = "Main",
                Attributes = MemberAttributes.Public | MemberAttributes.Static,
                ReturnType = new CodeTypeReference(typeof(void))
            };
            main.Statements.Add(new CodeExpressionStatement(new CodeMethodInvokeExpression(
                new CodeTypeReferenceExpression(typeof(Console)), "WriteLine",
                new CodeMethodInvokeExpression(new CodeObjectCreateExpression(spec.TypeName), spec.MethodName))));
            mainType.Members.Add(main);
            ns.Types.Add(mainType);
        }

        using var writer = new StringWriter();
        writer.WriteLine("// <auto-generated>");
        writer.WriteLine("// Generated from a reviewed LocalGPT CodeDOM declaration; execution requires separate user approval.");
        writer.WriteLine("// </auto-generated>");
        writer.WriteLine();
        provider.GenerateCodeFromCompileUnit(unit, writer, new CodeGeneratorOptions
        {
            BracingStyle = "C",
            BlankLinesBetweenMembers = true
        });
        return writer.ToString();
    }

    /// <summary>Rejects invalid type and method names rather than silently rewriting declarations.</summary>
    /// <param name="provider">Actual CodeDOM language provider.</param>
    /// <param name="name">The identifier to validate.</param>
    /// <param name="parameterName">The public field that contains it.</param>
    private void ValidateIdentifier(CodeDomProvider provider, string name, string parameterName)
    {
        if (string.IsNullOrWhiteSpace(name) || name.Length > 256 || !provider.IsValidIdentifier(name))
            throw new ArgumentException("Enter a valid C# identifier for " + parameterName + ".", parameterName);
    }

    /// <summary>Validates each namespace segment with the actual language provider.</summary>
    /// <param name="provider">Actual CodeDOM language provider.</param>
    /// <param name="name">The authored namespace.</param>
    private void ValidateNamespace(CodeDomProvider provider, string name)
    {
        if (string.IsNullOrWhiteSpace(name) || name.Length > 256)
            throw new ArgumentException("Enter a valid C# namespace.", nameof(name));
        foreach (var segment in name.Split('.'))
            ValidateIdentifier(provider, segment, nameof(name));
    }
}
